// Module-level stats singleton — reset at the top of scanLibrary(), printed at
// the bottom. Safe because exactly one scan runs at a time.
type ScanStats = {
  startedAtMs: number;
  directoriesWalked: number;
  audioFilesScanned: number;
  cueFilesInListings: number;
  booksTotal: number;
  // Cue-gate counters — mutually exclusive per book
  booksSkipMultiChapter: number; // chapters.length > 1
  booksSkipFromEmbedded: number; // metadata.fromEmbeddedChapters
  booksSkipNoCueSibling: number; // not in directory listing's cueBasenames
  booksCueProbeAttempted: number; // SAF read fired
  booksCueProbeSucceeded: number; // SAF read returned ≥1 chapter
  booksAutoGenerated: number; // auto-chapter generation ran
  // Wall-clock per phase (ms)
  msMediaStoreEnumerate: number;
  msMediaInfoNoCover: number;
  msMediaInfoWithCover: number;
  msCueProbe: number;
  msPersistBook: number; // includes artwork extraction + DB writes
};

